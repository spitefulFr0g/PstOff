use pstfree::convert::q21::derive;
use std::collections::BTreeMap;
fn main() {
    let mut p = BTreeMap::new();
    let mut checks = 0;
    assert!(derive(0x66120003, &p, 4, 2).is_none());
    checks += 1;
    p.insert(0x0042001f, vec![65, 0]);
    assert_eq!(derive(0x0042001f, &p, 4, 2).unwrap().0, vec![65, 0]);
    checks += 1;
    assert!(derive(0x0042001e, &p, 4, 2).is_none());
    checks += 1;
    p.insert(0x0e170003, vec![1, 0, 0, 0]);
    assert!(derive(0x0e170003, &p, 4, 2).is_none());
    checks += 1;
    assert_eq!(derive(0x67f20003, &p, 4, 2).unwrap().0, 4u32.to_le_bytes());
    checks += 1;
    assert_eq!(derive(0x67f10003, &p, 4, 2).unwrap().0, 2u32.to_le_bytes());
    checks += 1;
    assert_eq!(derive(0x65c60003, &p, 4, 2).unwrap().0, vec![0; 4]);
    checks += 1;
    assert!(derive(0x30130102, &p, 4, 2).is_none());
    checks += 1;
    p.insert(0x3016000b, vec![1]);
    p.insert(0x00710102, vec![1; 21]);
    assert!(derive(0x30130102, &p, 4, 2).is_none());
    checks += 1;
    p.insert(0x00710102, vec![1; 22]);
    assert_eq!(derive(0x30130102, &p, 4, 2).unwrap().0, vec![1; 16]);
    checks += 1;
    p.insert(0x0037001f, vec![1, 0, 1, 0, 65, 0]);
    assert_eq!(derive(0x0037001f, &p, 4, 2).unwrap().0, vec![65, 0]);
    checks += 1;
    p.insert(0x0037001f, vec![1, 0, 255, 0]);
    assert!(derive(0x0037001f, &p, 4, 2).is_none());
    checks += 1;
    p.insert(0x0e070003, 0x10u32.to_le_bytes().to_vec());
    assert_eq!(derive(0x0e1b000b, &p, 4, 2).unwrap().0, vec![1]);
    checks += 1;
    println!("policy_guards_passed={checks}");
}
